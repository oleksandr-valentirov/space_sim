//! CR3BP на межі означає те, що має означати (ROADMAP-UI.md, U6b2).
//!
//! `core-sys/tests/ffi.rs` уже звірив біти — але звірка межі з собою не
//! перевіряє **змісту**, і на це в цьому проєкті наступали двічі: спряжений
//! кватерніон (R1c) і сітка porkchop у чужих координатах (U5b) обидва
//! проходили бітову звірку бездоганно.
//!
//! Тому тут числа **ззовні**: опубліковані параметри системи Земля-Місяць і
//! геометрія, яку можна перевірити без нашого ж коду. Якщо декларація
//! переплутала порядок аргументів або одиниці, ці числа не зійдуться, хоч
//! біти й далі збігатимуться.

use core_rs::{cr3bp_jacobi, cr3bp_lagrange, cr3bp_mu, CoreError, Vec3d};

/// Гравітаційні параметри з ассета (`data/fixture/earth_moon.eph`, DE440),
/// м³/с². Ті самі числа, що друкує оракул.
const GM_EARTH: f64 = 398_600_435_436_000.0;
const GM_MOON: f64 = 4_902_800_066_000.0;

/// Середня відстань Земля-Місяць, метри — та сама, якою гра масштабує карту.
const L_M: f64 = 3.844e8;

/// Частка маси пари збігається з опублікованою — і розбіжність варта запису.
///
/// 0.0121505856 — класична стала Земля-Місяць (маса Місяця як 1/81.30056
/// земної), вписана в `engine::trajectory::MU`. З `mu` ассета (DE440) виходить
/// **0.0121505843**: різниця 1.3·10⁻⁹, тобто 1.1·10⁻⁷ відносно.
///
/// Це не помилка жодного з двох чисел — це два різні джерела, і саме ця
/// різниця пояснює 0.54 м, на які синодичні координати гри розходяться з
/// формулою рушія (`game/tests/scene.rs`, U6a2). Тому допуск тут названий, а
/// не підібраний: усе, що більше за 5·10⁻⁹, — уже інша система.
#[test]
fn the_mass_ratio_matches_the_published_one() {
    let mu = cr3bp_mu(GM_EARTH, GM_MOON);
    let classic = 0.012_150_585_609_624_04;
    println!(
        "  μ з ассета {mu:.12}, класична {classic:.12}, різниця {:.2e}",
        mu - classic
    );
    assert!(
        (mu - classic).abs() < 5e-9,
        "μ = {mu:.12}, а класична {classic:.12}"
    );
}

/// Точки Лагранжа стоять там, де їх міряють у кілометрах.
///
/// Оракул навмисно подвійний: L4 має **точну** формулу (`1/2 − μ`, `√3/2`), а
/// L1 і L2 — опубліковані відстані від Землі, 3.26·10⁸ і 4.49·10⁸ м. Перше
/// ловить помилку в осях, друге — в одиницях: безрозмірні координати, помножені
/// не на те, дали б правильну форму й неправильний масштаб.
#[test]
fn the_lagrange_points_land_where_they_are_measured() {
    let mu = cr3bp_mu(GM_EARTH, GM_MOON);

    let l4 = cr3bp_lagrange(mu, 4).expect("L4 рахується завжди — вона точна");
    assert!((l4.x - (0.5 - mu)).abs() < 1e-12, "L4.x = {}", l4.x);
    assert!(
        (l4.y - 3.0f64.sqrt() / 2.0).abs() < 1e-12,
        "L4.y = {}",
        l4.y
    );
    assert!(l4.z.abs() < 1e-15, "L4 вийшла з площини: z = {}", l4.z);

    // Відстань від **Землі**, а не від барицентра: Земля стоїть у −μ.
    for (point, published_m) in [(1, 3.26e8), (2, 4.49e8)] {
        let l = cr3bp_lagrange(mu, point).expect("L1 і L2 знаходяться бісекцією");
        let from_earth_m = (l.x + mu) * L_M;
        println!("  L{point} за {from_earth_m:.4e} м від Землі");
        assert!(
            (from_earth_m - published_m).abs() / published_m < 0.02,
            "L{point} за {from_earth_m:.4e} м, а міряють {published_m:.3e} м"
        );
    }

    // Точки поза 1..5 немає, і це відмова, а не мовчазний нуль.
    assert!(matches!(cr3bp_lagrange(mu, 6), Err(CoreError::InvalidArg)));
}

/// Константа Якобі в точці Лагранжа — це саме `2Ω` там, і зростає від L1 до L3.
///
/// Порядок `C(L1) > C(L2) > C(L3)` — підручникова властивість системи, а не
/// наше число: ворота відкриваються спершу до L1, потім до L2, потім до L3.
/// Помилка в порядку аргументів `(r, v, mu)` зруйнувала б саме її, лишивши
/// правдоподібні величини.
#[test]
fn the_jacobi_constant_orders_the_gates_the_way_the_textbook_does() {
    let mu = cr3bp_mu(GM_EARTH, GM_MOON);

    let c = |point: i32| {
        let l = cr3bp_lagrange(mu, point).expect("точка є");
        cr3bp_jacobi(l, Vec3d::default(), mu)
    };
    let (c1, c2, c3) = (c(1), c(2), c(3));
    println!("  C(L1) = {c1:.6}, C(L2) = {c2:.6}, C(L3) = {c3:.6}");

    assert!(
        c1 > c2,
        "C(L1) = {c1:.6} мала б бути більшою за C(L2) = {c2:.6}"
    );
    assert!(
        c2 > c3,
        "C(L2) = {c2:.6} мала б бути більшою за C(L3) = {c3:.6}"
    );

    // І порядок величини: для Земля-Місяць усі троє коло трьох.
    for (name, value) in [("C1", c1), ("C2", c2), ("C3", c3)] {
        assert!(
            (2.9..3.3).contains(&value),
            "{name} = {value:.6} — це вже не система Земля-Місяць"
        );
    }

    // Швидкість віднімається, а не додається: рухома точка має меншу `C`.
    let l1 = cr3bp_lagrange(mu, 1).expect("L1 є");
    let moving = cr3bp_jacobi(
        l1,
        Vec3d {
            x: 0.0,
            y: 0.1,
            z: 0.0,
        },
        mu,
    );
    assert!(moving < c1, "рух мав зменшити C: {moving:.6} проти {c1:.6}");
    assert!(
        (c1 - moving - 0.01).abs() < 1e-12,
        "C мала впасти рівно на v² = 0.01, а впала на {:.12}",
        c1 - moving
    );
}
