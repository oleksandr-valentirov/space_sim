//! Сітка porkchop: вибір вікна перельоту (ROADMAP-UI.md, U5b).
//!
//! ## Від чого й куди тут летять
//!
//! **Від апарата до тіла, у координатах центрального тіла.** Не від тіла до
//! тіла, і це виміряне рішення, а не смак.
//!
//! `porkchop_compute_eph` (U5a) робить розгортку тіло→тіло в тих координатах,
//! у яких лежить ассет. Для міжпланетного перельоту це те, що треба: центр
//! ассета за 1.1·10⁹ м від Сонця, тобто на тлі 1.5·10¹¹ м це майже воно.
//! Для Земля—Місяць — ні, і двічі:
//!
//! - **центр не там.** Фікстура баріцентрична: Земля лежить за 1.47·10¹¹ м
//!   від початку координат і летить зі швидкістю 30 км/с. Дуга Ламберта
//!   будується навколо початку координат, тож із `mu` Землі виходила дуга
//!   навколо Сонця з масою Землі — величина, якої не існує;
//! - **відходити нема звідки.** Взяти Землю тілом відходу означає `r1 = 0`,
//!   тобто виродження. Апарат же лежить на halo-орбіті за 4.5·10⁸ м від
//!   Землі, і питання, на яке відповідає плот, звучить «коли **мені** палити
//!   й скільки летіти», а не «коли Земля буде зручно розташована».
//!
//! Числа першого варіанта виглядали правдоподібно (2–9.6 км/с), і саме тому
//! це варто сказати вголос: **оракул U5a порівнював межу саму з собою** —
//! сітку з `lambert_solve`, — тож однакова помилка системи координат була по
//! обидва боки й скоротилася. Помилка вибору кадру не ловиться звіркою двох
//! шляхів; її ловить лише третє число ззовні, і тут це швидкість апарата
//! відносно Землі.
//!
//! Отже розгортка живе тут, а не в C: `lambert_solve` уже на межі й уже має
//! два незалежні оракули (D1), а стани відходу приходять із траєкторії, не з
//! ассета. Саме цю розвилку U5a й передбачив: «якщо обгортка почне обростати
//! параметрами — зупинитись». Обгортка лишається для тіло→тіло; борг на неї
//! записаний у ROADMAP (D9).
//!
//! ## Клітинка, якої немає, і клітинка, що коштує нуль
//!
//! Заборонені зони — властивість інструмента, а не помилка: porkchop-плот
//! існує саме для того, щоб їх було видно. Тому сітка щільна — `t1.len() *
//! tof.len()` комірок, — і в ній `None` там, де розв'язку немає.
//!
//! Різниця між `None` і `Some(0)` не педантична. Нуль — це найдешевший
//! переліт із можливих, тобто на плоті він виглядав би як **найкраще** вікно;
//! саме туди гравець і клікнув би.
//!
//! ## Чому рядками
//!
//! Одиниця роботи нитки — рядок, як ланка для прогнозу. Виміряно на фікстурі
//! (числа — у тесті `game/tests/porkchop.rs`): сітка не влазить у кадр, тож
//! рахує її нитка планувальника (правило 6 етапу U), але й «секунд чорного
//! екрана», яких боявся план кроку, тут немає — груба сітка зі згущенням
//! навколо мінімуму (розвилка U5b) не знадобилась.

use core_rs::{Ephemeris, State, Vec3d};

/// Клітинка сітки: чого коштує переліт, що починається в `t1` і триває `tof`.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Cell {
    /// Сам маневр відходу, інерціальні координати, м/с.
    ///
    /// Не «оцінка вартості», а той **самий** імпульс, який піде в план: дуга
    /// Ламберта тут будується від справжнього стану апарата, тож різниця між
    /// швидкістю на дузі й швидкістю апарата — це і є маневр. Тому клік по
    /// клітинці не рахує нічого заново (U5d).
    pub dv: [f64; 3],
    /// Величина того ж маневру — те, що показує курсор і чим фарбується плот.
    pub dv_m_s: f64,
    /// З якою швидкістю відносно тіла призначення апарат туди прийде.
    ///
    /// Це ціна **другого** маневру, ще не порахованого: гальмувати доведеться
    /// приблизно на стільки. Тому обидва числа й показуються окремо — вікно,
    /// дешеве на відході й нестерпне на приході, дешевим не є.
    pub v_inf_arrive: f64,
}

impl Cell {
    /// Ціна вікна одним числом — те, за чим плот фарбується й сортується.
    ///
    /// Сума двох маневрів, а не один із них: та сама арифметика, що в
    /// `VesselReadout::total_dv_m_s`, і з тієї ж причини — паливо витрачають
    /// обидва.
    pub fn total(&self) -> f64 {
        self.dv_m_s + self.v_inf_arrive
    }
}

/// Що порахувати.
///
/// Осі приходять готовими списками, а не «від, до, скільки»: хто малює вісь,
/// той і вирішує, як вона поділена, і сітка не мусить це вгадувати вдруге.
#[derive(Clone, Debug, PartialEq)]
pub struct GridRequest {
    pub id: u64,
    /// Стан апарата в кожен момент відходу — **зі снапшоту**, не з ассета.
    ///
    /// Звідси ж береться і вісь `t1`: два списки розійшлися б, а один не може.
    /// Викликач зобов'язаний брати ці стани лише з уже порахованого:
    /// `leg::state_at` за горизонтом віддає крайню точку, і сітка, побудована
    /// на ній, показувала б переліт із місця, де апарата не буде.
    pub depart: Vec<State>,
    /// Тіло призначення.
    pub arrive_body: i32,
    /// Тіло, навколо якого будується дуга. Його стан віднімається з обох
    /// кінців, бо задача Ламберта живе в координатах саме цього тіла.
    pub centre_body: i32,
    /// `mu` центрального тіла, прочитана з ассета один раз при старті
    /// (`Ephemeris::body_mu`, U5a) — правило 5 забороняє кликати ефемериду
    /// з кадру, а маса тіла не змінюється.
    pub mu: f64,
    pub prograde: bool,
    /// Тривалості перельоту, за зростанням.
    pub tof: Vec<f64>,
}

impl GridRequest {
    /// Моменти відходу — вісь `t1`.
    pub fn t1(&self) -> Vec<f64> {
        self.depart.iter().map(|s| s.t).collect()
    }
}

/// Порахована сітка. Не стан світу: планувальник у світ не пише нічого.
#[derive(Clone, Debug, PartialEq)]
pub struct Grid {
    /// Номер запиту, на який це відповідь.
    pub id: u64,
    pub t1: Vec<f64>,
    pub tof: Vec<f64>,
    /// `t1.len() * tof.len()` клітинок, рядок — один `t1`.
    pub cells: Vec<Option<Cell>>,
}

impl Grid {
    /// Клітинка за індексами осей.
    pub fn at(&self, i_t1: usize, i_tof: usize) -> Option<Cell> {
        if i_t1 >= self.t1.len() || i_tof >= self.tof.len() {
            return None;
        }
        self.cells[i_t1 * self.tof.len() + i_tof]
    }

    /// Найдешевше вікно: індекси осей і сама клітинка.
    ///
    /// `None`, якщо не зійшлося ніде — тобто весь плот заборонений. Такий
    /// результат теж треба показати, а не сховати за порожнім екраном.
    pub fn best(&self) -> Option<(usize, usize, Cell)> {
        let mut best: Option<(usize, usize, Cell)> = None;
        for (index, cell) in self.cells.iter().enumerate() {
            let Some(cell) = *cell else { continue };
            if best.is_none_or(|(_, _, was)| cell.total() < was.total()) {
                best = Some((index / self.tof.len(), index % self.tof.len(), cell));
            }
        }
        best
    }

    /// Межі шкали кольору — **не** справжній розмах цін.
    ///
    /// Верх обрізаний до [`SCALE_SPAN`] найдешевшого, і без цього плот був би
    /// одноколірним: виміряно на фікстурі — від 349 м/с до 3.4·10⁶ м/с, чотири
    /// порядки. Дорогі клітинки там не «трохи дорожчі», а недосяжні взагалі
    /// (переліт за добу через півсистеми), і віддавати їм увесь градієнт
    /// означало б розчавити в один колір саме ту область, де вибирають.
    ///
    /// Так само роблять і паперові porkchop-плоти: ізолінії малюють кратними
    /// мінімуму, а не від нуля до максимуму.
    pub fn scale(&self) -> Option<(f64, f64)> {
        let mut low = f64::INFINITY;
        let mut high: f64 = 0.0;
        for cell in self.cells.iter().flatten() {
            low = low.min(cell.total());
            high = high.max(cell.total());
        }
        if !low.is_finite() {
            return None;
        }
        Some((low, high.min(low * SCALE_SPAN)))
    }
}

/// У скільки разів за найдешевше вікно тягнеться шкала кольору.
///
/// Четверо: вікно, вчетверо дорожче за найкраще, — це вже «ні», а не «трохи
/// гірше», тож розрізняти всередині цієї межі нема чого. Число з практики
/// малювання плотів, не з фізики, і саме тому воно тут одне й видиме.
pub const SCALE_SPAN: f64 = 4.0;

/// Колір клітинки: RGBA, вісім біт на канал.
///
/// Дірка — **прозора**, і це не оформлення, а перевіркова властивість:
/// заборонена зона мусить читатися як «тут нічого немає», а не як клітинка з
/// якоюсь ціною. Будь-який непрозорий колір для неї, хоч чорний, лежав би на
/// тій самій шкалі, що й ціни, і око порівнювало б його з ними.
///
/// Решта — лінійна шкала від дешевого до дорогого. Свідомо не веселка: сім
/// кольорів дають сім хибних меж там, де величина міняється плавно. Палітра —
/// клопіт U7; тут важить лише те, що шкала монотонна й що обидва її кінці
/// відрізняються від дірки.
///
/// `low == high` (уся сітка однакова, або клітинка одна) дає дешевий кінець:
/// ділити на нуль нема потреби, і «все однакове» — це не «все найдорожче».
pub fn colour(cell: Option<Cell>, low: f64, high: f64) -> [u8; 4] {
    let Some(cell) = cell else {
        return [0, 0, 0, 0];
    };

    let span = high - low;
    let u = if span > 0.0 {
        ((cell.total() - low) / span).clamp(0.0, 1.0)
    } else {
        0.0
    };

    // Дешеве — холодне й темне, дороге — гаряче й світле.
    const CHEAP: [f64; 3] = [30.0, 70.0, 160.0];
    const COSTLY: [f64; 3] = [240.0, 200.0, 90.0];

    let mix = |a: f64, b: f64| (a + (b - a) * u).round() as u8;
    [
        mix(CHEAP[0], COSTLY[0]),
        mix(CHEAP[1], COSTLY[1]),
        mix(CHEAP[2], COSTLY[2]),
        255,
    ]
}

/// Яка клітинка під точкою, заданою часткою від лівого краю й від **низу**.
///
/// Частками, а не пікселями, і без жодного типу egui: так функція
/// перевіряється арифметикою, а віджет лишається тонким. Знизу — бо на плоті
/// вісь `tof` росте вгору, як на всіх porkchop-плотах, тоді як рядки
/// зображення йдуть згори вниз; місце, де цей переворот забувають, виглядає
/// як цілком правдоподібний плот із дзеркальною відповіддю.
///
/// `None` — точка поза плотом. Клітинка-дірка натомість повертається як
/// звичайна: курсор мусить сказати «тут розв'язку немає», а не мовчати.
pub fn cell_at(grid: &Grid, from_left: f32, from_bottom: f32) -> Option<(usize, usize)> {
    if grid.t1.is_empty() || grid.tof.is_empty() {
        return None;
    }
    if !(0.0..1.0).contains(&from_left) || !(0.0..1.0).contains(&from_bottom) {
        return None;
    }
    let i = (f64::from(from_left) * grid.t1.len() as f64) as usize;
    let j = (f64::from(from_bottom) * grid.tof.len() as f64) as usize;
    Some((i.min(grid.t1.len() - 1), j.min(grid.tof.len() - 1)))
}

/// Один рядок сітки: усі `tof` для одного моменту відходу.
///
/// Рядок, а не вся сітка, — щоб між рядками нитка встигала подивитись у канал
/// (див. вступ модуля). Рядок із самих дірок — нормальний результат: так
/// виглядає момент, для якого ефемерида не має станів.
pub fn row(eph: &Ephemeris, request: &GridRequest, i_t1: usize) -> Vec<Option<Cell>> {
    let mut dense = vec![None; request.tof.len()];
    let Some(&from) = request.depart.get(i_t1).as_ref() else {
        return dense;
    };

    // Центр — один раз на рядок: він потрібен обом кінцям, але на відході
    // час той самий для всієї строки.
    let Ok(centre_at_t1) = eph.body_state(request.centre_body, from.t) else {
        return dense;
    };
    let r1 = sub(from.r, centre_at_t1.r);
    let v1 = sub(from.v, centre_at_t1.v);

    for (j, &tof) in request.tof.iter().enumerate() {
        // Недодатна тривалість — не переліт; `lambert_solve` відмовив би сам,
        // але дірка з цієї причини не варта виклику через межу.
        if tof <= 0.0 {
            continue;
        }
        let t2 = from.t + tof;

        // За краєм ассета станів немає — клітинка лишається діркою.
        let (Ok(centre), Ok(target)) = (
            eph.body_state(request.centre_body, t2),
            eph.body_state(request.arrive_body, t2),
        ) else {
            continue;
        };
        let r2 = sub(target.r, centre.r);
        let v2 = sub(target.v, centre.v);

        // Ламберт не зійшовся — теж дірка, і теж очікувана: вироджена
        // геометрія й недосяжна тривалість — звичайна частина плоту.
        let Ok((depart, arrive)) =
            core_rs::lambert_solve(r1, r2, tof, request.mu, request.prograde, 0)
        else {
            continue;
        };

        let dv = sub(depart, v1);
        dense[j] = Some(Cell {
            dv: [dv.x, dv.y, dv.z],
            dv_m_s: length(dv),
            v_inf_arrive: length(sub(arrive, v2)),
        });
    }

    dense
}

fn sub(a: Vec3d, b: Vec3d) -> Vec3d {
    Vec3d {
        x: a.x - b.x,
        y: a.y - b.y,
        z: a.z - b.z,
    }
}

fn length(v: Vec3d) -> f64 {
    (v.x * v.x + v.y * v.y + v.z * v.z).sqrt()
}

// Функції «порахуй усю сітку одним махом» тут немає навмисно: єдиний, кому
// сітка потрібна, — нитка планувальника, а їй потрібні перерви між рядками
// (`crate::planner::sweep`). Зручний обгортковий виклик означав би другий шлях
// до тієї самої відповіді, який ніхто не проганяє, — те саме, що структура,
// жодне поле якої не читається.
