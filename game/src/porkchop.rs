//! Сітка porkchop: вибір вікна перельоту (ROADMAP-UI.md, U5b).
//!
//! Межа вже вміє віддати сітку одним пакетом (`core_rs::porkchop`, U5a). Тут —
//! те, чого межа не знає й знати не мусить: **у якому вигляді сітка доходить
//! до екрана** і **чому вона рахується рядками**.
//!
//! ## Клітинка, якої немає, і клітинка, що коштує нуль
//!
//! C повертає лише ті клітинки, де Ламберт зійшовся, і це не помилка, а
//! властивість інструмента: porkchop-плот завжди має заборонені зони, і плот
//! існує саме для того, щоб їх було видно (`core/planning/porkchop.h`). Але
//! список, з якого клітинки просто випали, для малювання не годиться — по
//! ньому не скажеш, **де** дірка. Тому сітка тут щільна: `t1.len() *
//! tof.len()` комірок, і `None` там, де розв'язку немає.
//!
//! Різниця між `None` і `Some(0)` — не педантизм. Нуль — це найдешевший
//! переліт із можливих, тобто на плоті він виглядав би як **найкраще** вікно;
//! саме туди гравець і клікнув би.
//!
//! ## Чому рядками
//!
//! Виміряно цією сесією на фікстурі `data/fixture/earth_moon.eph`: сітка
//! 100×100 коштує **22 мс**, один рядок (100 клітинок) — **0.24 мс**. Отже
//! два висновки, обидва потрібні:
//!
//! - у кадр сітка не влазить (22 мс проти бюджету 16.7 мс на 60 Hz), тож
//!   рахує її нитка планувальника — правило 6 етапу U;
//! - але й «секунди чорного екрана», яких боявся план кроку, тут немає, і
//!   груба сітка зі згущенням навколо мінімуму (розвилка U5b) не потрібна.
//!
//! Рядок — одиниця роботи цієї нитки, як ланка для прогнозу: 0.24 мс між
//! перевірками каналу означає, що тягнення вузла не чекає на сітку довше, ніж
//! на один рядок.

use core_rs::Ephemeris;

/// Клітинка сітки: чого коштує переліт, що починається в `t1` і триває `tof`.
///
/// Обидва числа читаються нарізно — колір бере суму, курсор показує кожне, —
/// і саме тому їх тут два, а не одне.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Cell {
    /// З чим треба відірватися від тіла відходу.
    pub v_inf_depart: f64,
    /// З чим прилетиш до тіла призначення.
    pub v_inf_arrive: f64,
}

impl Cell {
    /// Ціна вікна одним числом — те, за чим плот фарбується й сортується.
    ///
    /// Сума, а не норма суми й не одне з двох: обидва кінці треба відпрацювати
    /// двигуном, і вікно, дешеве на відході й нестерпне на приході, дешевим
    /// не є. Це та сама арифметика, що в `VesselReadout::total_dv_m_s`.
    pub fn total(&self) -> f64 {
        self.v_inf_depart + self.v_inf_arrive
    }
}

/// Що порахувати.
///
/// Осі приходять готовими списками, а не «від, до, скільки»: хто малює вісь,
/// той і вирішує, як вона поділена, і сітка не мусить це вгадувати вдруге.
#[derive(Clone, Debug, PartialEq)]
pub struct GridRequest {
    pub id: u64,
    pub depart_body: i32,
    pub arrive_body: i32,
    /// `mu` центрального тіла перельоту — того, чия гравітація тримає дугу.
    ///
    /// Числом, а не ідентифікатором тіла, і читається воно з ассета
    /// (`Ephemeris::body_mu`, U5a) рівно один раз при старті — так само, як
    /// радіус Землі для панелі висоти (U2a). Причина та сама: маса тіла не
    /// змінюється, а правило 5 забороняє кликати ефемериду з кадру.
    pub mu: f64,
    pub prograde: bool,
    /// Моменти відходу, за зростанням.
    pub t1: Vec<f64>,
    /// Тривалості перельоту, за зростанням.
    pub tof: Vec<f64>,
}

/// Порахована сітка. Не стан світу: планувальник у світ не пише нічого.
#[derive(Clone, Debug, PartialEq)]
pub struct Grid {
    /// Номер запиту, на який це відповідь.
    pub id: u64,
    pub t1: Vec<f64>,
    pub tof: Vec<f64>,
    /// `t1.len() * tof.len()` клітинок, рядок — один `t1`.
    pub cells: Vec<Option<Cell>>,
}

impl Grid {
    /// Клітинка за індексами осей.
    pub fn at(&self, i_t1: usize, i_tof: usize) -> Option<Cell> {
        if i_t1 >= self.t1.len() || i_tof >= self.tof.len() {
            return None;
        }
        self.cells[i_t1 * self.tof.len() + i_tof]
    }

    /// Найдешевше вікно: індекси осей і сама клітинка.
    ///
    /// `None`, якщо не зійшлося ніде — тобто весь плот заборонений. Такий
    /// результат теж треба показати, а не сховати за порожнім екраном.
    pub fn best(&self) -> Option<(usize, usize, Cell)> {
        let mut best: Option<(usize, usize, Cell)> = None;
        for (index, cell) in self.cells.iter().enumerate() {
            let Some(cell) = *cell else { continue };
            if best.is_none_or(|(_, _, was)| cell.total() < was.total()) {
                best = Some((index / self.tof.len(), index % self.tof.len(), cell));
            }
        }
        best
    }

    /// Від якої ціни до якої — межі шкали кольору.
    pub fn range(&self) -> Option<(f64, f64)> {
        let mut range: Option<(f64, f64)> = None;
        for cell in self.cells.iter().flatten() {
            let total = cell.total();
            range = Some(match range {
                Some((low, high)) => (low.min(total), high.max(total)),
                None => (total, total),
            });
        }
        range
    }
}

/// Один рядок сітки: усі `tof` для одного `t1`.
///
/// Рядок, а не вся сітка, — щоб між рядками нитка встигала подивитись у канал
/// (див. вступ модуля). Порожній результат — нормальний: так виглядає момент
/// відходу, для якого ефемерида не має стану, і C у такому разі пропускає
/// **весь** рядок (`core/planning/porkchop.c`).
pub fn row(eph: &Ephemeris, request: &GridRequest, i_t1: usize) -> Vec<Option<Cell>> {
    let mut dense = vec![None; request.tof.len()];
    let Some(&t1) = request.t1.get(i_t1) else {
        return dense;
    };

    let Ok(sparse) = core_rs::porkchop(
        eph,
        request.depart_body,
        request.arrive_body,
        request.mu,
        request.prograde,
        std::slice::from_ref(&t1),
        &request.tof,
    ) else {
        // Сітка з одного `t1` не буває завеликою для власного буфера, а
        // порожні осі сюди не доходять (`grid` їх не питає). Лишається
        // `mu <= 0` — тіло, маси якого ассет не знає; тоді рядок і справді
        // порожній, і таким його треба показати.
        return dense;
    };

    // Дві впорядковані послідовності, і C копіює `tof` у клітинку бітово
    // (`out[n].tof = tof_grid[j]`), тож збіг перевіряється рівністю без
    // жодного допуску. Обхід у два вказівники, а не пошук: клітинки йдуть
    // у тому самому порядку, що й вісь, і зустрічний рух це стверджує —
    // якби C колись почав віддавати їх інакше, тут би лишилися дірки, а не
    // тихо переплутані стовпці.
    let mut j = 0;
    for cell in sparse {
        while j < request.tof.len() && request.tof[j] != cell.tof {
            j += 1;
        }
        if j >= request.tof.len() {
            break;
        }
        dense[j] = Some(Cell {
            v_inf_depart: cell.v_inf_depart,
            v_inf_arrive: cell.v_inf_arrive,
        });
        j += 1;
    }

    dense
}

// Функції «порахуй усю сітку одним махом» тут немає навмисно: єдиний, кому
// сітка потрібна, — нитка планувальника, а їй потрібні перерви між рядками
// (`crate::planner::sweep`). Зручний обгортковий виклик означав би другий шлях
// до тієї самої відповіді, який ніхто не проганяє, — те саме, що структура,
// жодне поле якої не читається.
