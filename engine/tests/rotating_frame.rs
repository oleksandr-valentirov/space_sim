//! Число, на якому стоїть рішення U6a1 (ROADMAP-UI.md).
//!
//! Перетворення обертового фрейму рахується на CPU у `f64`, а не у вертексному
//! шейдері, і причина — не смак, а розбіжність у метрах. Тут вона й
//! перевіряється: якщо колись хтось повернеться до `f32`-шляху, це число має
//! стояти перед ним, а не бути забутим у комітах.
//!
//! Тест не потребує ні GPU, ні вікна: обидва шляхи — арифметика над тією
//! самою фікстурою halo-орбіти.

use engine::rotating_probe::{cost, error_px, precision};
use engine::trajectory;

/// Шлях через `f32` втрачає сотні метрів, і на близькому вигляді це видно.
#[test]
fn the_float_path_loses_enough_metres_to_show() {
    let samples = trajectory::load();
    let p = precision(&samples);

    println!(
        "  f32-шлях: найгірше {:.1} м (семпл {}), у середньому {:.1} м",
        p.worst_m, p.worst_sample, p.mean_m
    );

    // Межі широкі навмисно: це не константа, яку ми обираємо, а властивість
    // `f32` на 4·10⁸ м. Тест ловить не «число змінилось на відсоток», а
    // «шлях раптом став точним» або «став катастрофічним».
    assert!(
        (50.0..500.0).contains(&p.worst_m),
        "найгірша розбіжність {:.1} м — це вже не той порядок, на якому \
         ухвалено U6a1",
        p.worst_m
    );
    assert!(
        p.mean_m > 10.0,
        "середня розбіжність {:.1} м — надто мала, щоб виправдовувати рішення",
        p.mean_m
    );

    // При вигляді завширшки 10 км помилка більша за піксель на порядок; при
    // вигляді на всю систему Земля-Місяць її не видно взагалі. Обидва боки, бо
    // одне число без другого виглядало б вироком усьому `f32` в рендері.
    let close = error_px(p.worst_m, 1.0e4);
    let far = error_px(p.worst_m, 1.0e9);
    println!("  на 10 км кадру: {close:.1} px, на 10⁶ км: {far:.3} px");
    assert!(close > 10.0, "на близькому вигляді помилка {close:.1} px");
    assert!(far < 0.1, "на далекому вигляді помилка {far:.3} px");
}

/// Перетворення на CPU дорожчає прохід, який там уже є, — але лишається
/// одним проходом.
///
/// Час машинозалежний, тому перевіряється не мілісекунда, а порядок: обидва
/// числа з одного прогону, і друге не має бути в рази більшим за перше.
#[test]
fn the_cpu_path_costs_a_few_nanoseconds_a_point() {
    let samples = trajectory::load();
    let c = cost(&samples, 50);

    println!(
        "  camera-relative {:.2} нс, з перетворенням {:.2} нс ({:+.0}%)",
        c.camera_ns,
        c.camera_and_frame_ns,
        c.overhead()
    );

    assert!(
        c.camera_and_frame_ns > c.camera_ns,
        "перетворення не може бути безкоштовним: {:.2} проти {:.2} нс",
        c.camera_and_frame_ns,
        c.camera_ns
    );
    assert!(
        c.camera_and_frame_ns < 20.0 * c.camera_ns,
        "перетворення коштує {:.2} нс проти {:.2} — це вже не той самий прохід",
        c.camera_and_frame_ns,
        c.camera_ns
    );
}
