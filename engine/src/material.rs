//! Правило матеріалу: колір поверхні від нахилу й рельєфу (ROADMAP, T4).
//!
//! Колірний тайлсет Місяця несе шість рівнів, тобто вузол завширшки ~2.7 км, а
//! джерело (LROC WAC) — 100 м на піксель, з якого кукер бере точкову вибірку.
//! Рельєфу ж [`crate::detail`] дорощує октави аж до ~106 м. Отже зблизька гори
//! гострі, а колір поверх них — рівна пляма, і різниця між ними росте з кожним
//! кроком камери вниз.
//!
//! Заповнити цю різницю другою текстурою не можна: її просто немає. Тому те
//! саме, що R7c зробив висоті, тут робиться кольору — **правилом**, а не
//! даними: яскравість зсувається від нахилу місцевості й від процедурного
//! рельєфу, який на ній стоїть.
//!
//! ## Чому саме нахил і рельєф, а не висота над сферою
//!
//! Висота над опорним радіусом уже **є** в кольорі: моря лежать нижче й
//! темніші, материки вище й світліші, і мозаїка це знає з вимірів. Правило,
//! яке додало б до цього власну залежність від висоти, малювало б поверх даних
//! другу відповідь на те саме питання — і на Землі (T7) розійшлося б з
//! батиметрією видимо.
//!
//! Нахил такого дубля не має: на масштабі вузла мозаїки його не видно взагалі,
//! а фізика за ним справжня — на крутому схилі реголіт зсувається, оголюючи
//! світліший незрілий матеріал; саме тому стінки свіжих кратерів світлі.
//!
//! ## Три правила, успадковані від деталі висоти
//!
//! **1. Аргументи — величини, а не стан ассета.** `slope` приходить у
//! радіанах-на-одиницю, `detail_m` у метрах, нормувальник — з **радіуса тіла**
//! ([`crate::detail::base_m`]). Глибина піраміди в правило не входить ніде:
//! перекукування ассета з іще одним рівнем не має права перефарбувати схил, як
//! не має права переграти гори.
//!
//! **2. Рахується у вершині, і саме тому шва немає.** Обидва аргументи вже
//! пораховані `vertex_terrain` і обидва на спільному вузлі двох патчів **бітово
//! одні** — `slope` за R7c, `detail_m` як функція нормалі з буфера геометрії.
//! Отже неперервність кольору на межі рівнів не доводиться, а успадковується.
//!
//! ⚠ Спокуса взяти нахил з `ddx/ddy` у фрагменті сильна — там лежить справжня
//! геометрична нормаль зі всім рельєфом, і безкоштовно. Але вона нормаль
//! **трикутника**, тобто функція рівня патча: два сусіди різних рівнів дали б
//! на спільному ребрі два різні кольори, і шов ліг би рівно там, де R2b його
//! прибрав.
//!
//! **3. Рівнина лишається рівниною.** Обидва доданки пропорційні нахилу
//! місцевості (`detail_m` — лінійно за побудовою), тож на дні моря правило
//! повертає рівно одиницю, а не «майже одиницю»: колір там лишається тим, що
//! виміряв WAC.

use crate::detail;

/// Наскільки яскравіший найкрутіший схил за рівнину.
///
/// Параметр вигляду, не виміряна величина: справжній фотометричний контраст
/// свіжого реголіту залежить від фазового кута, якого в кадрі ще немає. Міняти
/// вільно, доки перевірки етапу зелені.
pub const SLOPE_GAIN: f64 = 0.30;

/// Нахил, на якому підсвітка схилу виходить на повну.
///
/// 0.3 — це ~17°, приблизно кут природного укосу реголіту: крутіше за нього
/// схил не тримається взагалі, тож насичення саме там і має бути.
pub const SLOPE_REF: f64 = 0.30;

/// Наскільки гребінь процедурного рельєфу світліший за сусідню западину.
///
/// Множник до **нормованого** рельєфу, тобто до числа порядку одиниці. Разом з
/// нормуванням на [`SLOPE_REF`] це означає: на схилі в 17° розкид яскравості
/// від рельєфу — приблизно ±0.3, а на рівнині нульовий.
pub const RELIEF_GAIN: f64 = 0.45;

/// Межі множника.
///
/// Не косметика: альбедо не буває від'ємним, а множник більший за ~2 вибив би
/// найсвітліші ділянки мозаїки за край шкали ще до тонмапера (той приходить
/// у T5).
pub const MIN_TINT: f64 = 0.35;
/// Верхня межа множника, пара до [`MIN_TINT`].
pub const MAX_TINT: f64 = 1.80;

/// Множник альбедо у вузлі.
///
/// * `slope` — нахил місцевості, [`crate::tiles::Terrain::slope_at`];
/// * `detail_m` — висота процедурної деталі в цьому ж вузлі, метри
///   ([`crate::detail::height_m`]);
/// * `base_m` — довжина хвилі найгрубішої октави, [`crate::detail::base_m`].
///
/// ⚠ `base_m` тут не для того, щоб перевести метри в метри, а щоб зробити
/// рельєф **безрозмірним однаково для будь-якого тіла**: деталь має амплітуду
/// `STEEPNESS · slope · λ`, тож поділ на `STEEPNESS · base_m` лишає число
/// порядку `slope`, а поділ на [`SLOPE_REF`] — порядку одиниці. Тіло вдвічі
/// більше дістає вдвічі довші хвилі й той самий контраст.
pub fn tint(slope: f64, detail_m: f64, base_m: f64) -> f64 {
    let steep = (slope / SLOPE_REF).clamp(0.0, 1.0);
    let relief = detail_m / (detail::STEEPNESS * base_m * SLOPE_REF);
    (1.0 + SLOPE_GAIN * steep + RELIEF_GAIN * relief).clamp(MIN_TINT, MAX_TINT)
}

#[cfg(test)]
mod tests {
    use super::*;

    const RADIUS: f64 = 1_737_400.0;

    /// На рівнині правило не робить **нічого** — і саме рівно нічого.
    ///
    /// Бітова одиниця, а не «близько до одиниці»: на дні моря колір мусить
    /// лишитися тим, що виміряв WAC, і кадр із пласким рельєфом мусить бути
    /// той самий, що до T4. Це ж і оракул того, що T4 не зрушив жодного
    /// попереднього знімка.
    #[test]
    fn flat_ground_keeps_the_colour_the_mosaic_measured() {
        let got = tint(0.0, 0.0, detail::base_m(RADIUS));
        assert_eq!(got.to_bits(), 1.0f64.to_bits(), "рівнина дала {got}");
    }

    /// Крутіший схил світліший, і монотонно.
    #[test]
    fn a_steeper_slope_is_brighter() {
        let base = detail::base_m(RADIUS);
        let mut previous = f64::NEG_INFINITY;
        for step in 0..32 {
            let slope = f64::from(step) * 0.02;
            let got = tint(slope, 0.0, base);
            assert!(
                got >= previous - 1e-15,
                "нахил {slope:.2} дав {got:.4} після {previous:.4}"
            );
            previous = got;
        }
        // І підсвітка справді насичується там, де сказано.
        let at_ref = tint(SLOPE_REF, 0.0, base);
        let beyond = tint(SLOPE_REF * 3.0, 0.0, base);
        assert_eq!(
            at_ref.to_bits(),
            beyond.to_bits(),
            "насичення не спрацювало"
        );
        assert!((at_ref - (1.0 + SLOPE_GAIN)).abs() < 1e-12);
    }

    /// Гребінь світліший за западину, і симетрично.
    #[test]
    fn a_crest_is_brighter_than_the_hollow_beside_it() {
        let base = detail::base_m(RADIUS);
        // Амплітуда деталі на схилі в `SLOPE_REF`, найгрубіша октава на повну.
        let amplitude = detail::STEEPNESS * SLOPE_REF * base * 0.5;
        let crest = tint(SLOPE_REF, amplitude, base);
        let hollow = tint(SLOPE_REF, -amplitude, base);
        println!("  гребінь {crest:.4}, западина {hollow:.4}");
        assert!(
            crest > hollow,
            "гребінь {crest:.4} не світліший за {hollow:.4}"
        );
        let flat = tint(SLOPE_REF, 0.0, base);
        assert!(
            ((crest - flat) - (flat - hollow)).abs() < 1e-12,
            "рельєф зсунув середню яскравість схилу"
        );
    }

    /// Множник не виходить за межі й не стає NaN на жодному вході.
    ///
    /// Включно з тими, яких не буває: від'ємний нахил, деталь у сто разів вища
    /// за свою амплітуду. Правило живе в шейдері, де перевіряти вхід нічим.
    #[test]
    fn the_tint_never_leaves_its_bounds() {
        let base = detail::base_m(RADIUS);
        for slope in [-1.0, 0.0, 0.01, 0.3, 1.0, 10.0, 1e6] {
            for detail_m in [-1e6, -1e3, 0.0, 1e3, 1e6] {
                let got = tint(slope, detail_m, base);
                assert!(got.is_finite(), "нахил {slope}, деталь {detail_m} → {got}");
                assert!(
                    (MIN_TINT..=MAX_TINT).contains(&got),
                    "нахил {slope}, деталь {detail_m} → {got}"
                );
            }
        }
    }

    /// Нормувальник мусить приходити з тіла, а не з ассета — і це видно числом.
    ///
    /// Підміна `detail::base_m` на `Terrain::step_m` напрошується сама:
    /// «деталь починається там, де кінчаються дані» — так і написано в
    /// [`crate::tiles::Terrain::step_m`], і для **висоти** це правда. Для
    /// кольору та сама підміна означала б, що перекукування ассета з іще одним
    /// рівнем перефарбовує схил.
    ///
    /// Тест показує ціну помилки, а не сигнатуру: два тайлсети того самого
    /// тіла різної глибини дають два різні кроки, і правило на них — два різні
    /// кольори. `base_m` натомість однаковий за побудовою.
    #[test]
    fn the_normaliser_comes_from_the_body_not_from_the_asset() {
        use crate::tiles::{Terrain, STORED};

        let build = |levels: u32| {
            let grids = vec![vec![0i16; STORED * STORED]; Terrain::count(levels)];
            Terrain::build(levels, RADIUS, 0.5, &grids)
        };
        let (shallow, deep) = (build(2), build(4));
        assert_eq!(
            shallow.reference_m, deep.reference_m,
            "тіло мусить бути одне"
        );

        // Деталь порядку власної амплітуди на кроці глибшої піраміди
        // (`0.5 · STEEPNESS · slope · step`): менше число нічого не сказало б,
        // бо доданок нахилу від нормувальника не залежить узагалі.
        let (slope, detail_m) = (0.2, 1000.0);
        let wrong = (
            tint(slope, detail_m, shallow.step_m()),
            tint(slope, detail_m, deep.step_m()),
        );
        println!("  на кроках піраміди: {:.4} проти {:.4}", wrong.0, wrong.1);
        assert!(
            (wrong.0 - wrong.1).abs() > 0.05,
            "фікстура беззуба: обидві глибини дали той самий колір"
        );

        assert_eq!(
            tint(slope, detail_m, detail::base_m(shallow.reference_m)).to_bits(),
            tint(slope, detail_m, detail::base_m(deep.reference_m)).to_bits(),
            "нормувальник перестав бути функцією самого тіла"
        );
    }
}
