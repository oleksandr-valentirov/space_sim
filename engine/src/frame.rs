/// The format the scene is drawn into -- **before** luminances are compressed.
///
/// WARNING: not the target's format, and that is the point of step T5c3. With
/// materials, values above one appeared in the frame (the hull's highlight at
/// `roughness = 0.35` is about 3.7), while the composition of aerial perspective
/// **reads** what is already drawn (`dst*T` and `dst + L`, S5). Compressing in
/// every shader would mean multiplying and adding already-compressed numbers,
/// i.e. spoiling the air; compressing afterwards means having an intermediate
/// target in which one is not the ceiling.
pub const HDR_FORMAT: wgpu::TextureFormat = wgpu::TextureFormat::Rgba16Float;

