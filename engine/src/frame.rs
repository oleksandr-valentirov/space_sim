/// The clear colour, **in linear light**. Not black deliberately: a black frame
/// and a frame that never happened look the same, and a check for "something got
/// drawn" is worth nothing against black.
///
/// WARNING: the numbers look odd, and they are exactly that because they are not
/// picked but **derived**: the target encodes gamma (T5a), so the source of
/// truth stays [`CLEAR_BYTES`] -- the look of the sky chosen by eye -- and what
