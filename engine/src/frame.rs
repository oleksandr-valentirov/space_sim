//! What exactly gets drawn. Nothing here knows about the window -- only about
//! the texture to write into, its format and its size.
//!
//! The format is in the constructor rather than in `draw`, because the pipeline
//! is bound to the target's format. A window and a screenshot have different
//! formats, so they have different [`Frame`]s -- and that is the same reason
//! they give slightly different pixels: the window surface is sRGB, the
//! screenshot target linear. The colours in the shader are the same; what the
//! hardware does with them on write is not.
//!
//! ## Why a sphere here and not a triangle (ROADMAP I1)
//!
//! Before I1 the frame drew F2's triangle, while everything measured in stage F
//! -- reversed-Z, camera-relative, real scale -- lived in separate self-contained
//! paths (`depth_probe`, `sphere_render`, `flight_probe`), each with its own
//! pipeline and its own depth texture. That is, none of those properties was
//! checked on the path by which the frame actually reaches the window, and
//! `--perf-probe` was measuring the ceiling of synchronisation rather than the
//! scene.
//!
//! Those paths remain: they measure one statement each and do it better than an
//! interactive frame could. What stays shared between them is everything that
//! does the arithmetic: `sphere::Mesh`, `camera::Camera`, `depth`, the same
//! `sphere.wgsl`.

