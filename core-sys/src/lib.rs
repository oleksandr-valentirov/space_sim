//! Сирі FFI-декларації числового ядра (PROJECT.md §5).
//!
//! Порожньо, і це стан кроку, а не недогляд. D1 переносить **збірку** C у
//! `build.rs`; декларації — це D2, і вони пишуться **вручну**, без bindgen.
//!
//! Причина руками, а не bindgen: межа мала (лічені функції), а bindgen тягне
//! залежність від libclang і генерує те, що ніхто не читає. Тут кожен рядок
//! має бути прочитаний очима — це єдине місце, де помилка в типі не
//! діагностується, а просто дає неправильні числа.
//!
//! Що з'явиться на D2: `eph_load`, `eph_body_state`, `eph_free`.
//!
//! Безпечна обгортка — не тут, а в `core-rs` (D3). У цьому крейті немає нічого,
//! крім оголошень; увесь наш `unsafe` живе в одному місці, і це не тут.

