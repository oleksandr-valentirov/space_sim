//! Читач ETOPO 2022: форма Землі (етап T, крок T7b).
//!
//! Поділ оракулів той самий, що у WAC, і за тією ж причиною — за тим, що
//! кожен здатен зловити сам і що для нього мусить лежати на диску:
//!
//! 1. **заголовок** — прив'язка й реєстрація. Перевіряється окремо від
//!    пікселів, бо в git лежить рівно він (466 МБ продукту — ні, Q5), і бо
//!    жодна помилка в ньому не видна на картинці;
//! 2. **частка суші** — одне число на весь клас помилок геометрії. Справжня
//!    — 29.2%; зсув на пів пікселя, перевернутий порядок рядків чи хибно
//!    розібраний предиктор рухають його на відсотки;
//! 3. **названі точки** — орієнтація, і вона розпадається на два твердження,
//!    а не одне. Широту ловить пара полюсів: північний — океан, південний —
//!    лід. Довготу вона **не** ловить, і для неї стоїть окрема пара
//!    дзеркальних меридіанів.
//!
//! Усе, що потребує самих даних, пропускається без них — і каже, чого бракує.

use dem_cook::etopo::{Header, Relief};
use std::path::{Path, PathBuf};

fn data(name: &str) -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../data/etopo")
        .join(name)
}

/// Сам продукт, або `None` — тоді тест каже, чого бракує, і не падає (Q5).
fn relief() -> Option<Relief> {
    let path = data("etopo_2022_60s_surface.tif");
    match Relief::read(&path) {
        Ok(grid) => Some(grid),
        Err(_) => {
            eprintln!(
                "ПРОПУЩЕНО: немає {}. Як покласти назад — data/etopo/README.md",
                path.display()
            );
            None
        }
    }
}

/// Заголовок читається з етикетки — тобто з тих 32 КіБ, які лежать у git.
///
/// Це і є сенс етикетки: розбір прив'язки перевіряється там, де самих даних
/// може не бути взагалі — на CI, на чужій машині, у свіжому клоні.
#[test]
fn header_from_label() {
    let header = Header::read(&data("etopo_2022_60s_surface.lbl")).expect("етикетка в git");

    assert_eq!(header.samples, 21600);
    assert_eq!(header.lines, 10800);
    assert!(
        (header.per_degree - 60.0).abs() < 1e-9,
        "60 відліків на градус, а вийшло {}",
        header.per_degree
    );
    assert_eq!(header.corner_deg, (-180.0, 90.0));
    assert!(
        header.covers_globe(),
        "сітка мусить накривати глобус цілком"
    );
}

/// Обрізана етикетка — не менш валідний TIFF для заголовка, але не для даних.
///
/// Перевірка тут не про сам файл, а про межу: `Header::read` мусить працювати
/// без пікселів, а `Relief::read` — падати, а не читати сміття. Інакше кукер
/// одного дня скукав би тайлсет з етикетки й нічого не сказав.
#[test]
fn label_is_not_data() {
    let path = data("etopo_2022_60s_surface.lbl");
    assert!(Header::read(&path).is_ok());
    assert!(
        Relief::read(&path).is_err(),
        "з 32 КіБ голови не можна прочитати 933 МБ відліків"
    );
}

/// Частка суші — головний оракул геометрії, одне число на весь клас.
#[test]
fn land_fraction_matches_the_planet() {
    let Some(grid) = relief() else { return };

    let land = grid.land_fraction();
    assert!(
        (land - 0.2911).abs() < 0.002,
        "частка суші {:.4}, а Земля має 0.292",
        land
    );
}

/// Діапазон висот: найглибша западина й найвища гора, обидві усереднені
/// коміркою 1.85 км.
///
/// Числа менші за підручникові (−10 935 і 8849) саме на це усереднення, і це
/// не похибка читача, а роздільність продукту. Оракул тут — не «схоже на
/// правду», а незалежна реалізація читача на Python, яка дала ті самі два
/// числа з тих самих байтів.
#[test]
fn range_matches_the_product() {
    let Some(grid) = relief() else { return };

    assert_eq!(grid.measured(), (-10752, 8157));
}

/// Широту ловлять полюси: північний — океан, південний — лід на три кілометри.
///
/// Перевернутий порядок рядків міняє їх місцями, і жоден інший оракул цього
/// не бачить: частка суші від перевороту не міняється взагалі.
#[test]
fn poles_are_not_swapped() {
    let Some(grid) = relief() else { return };
    let degrees = std::f64::consts::PI / 180.0;

    let north = grid.sample_m(89.9 * degrees, 0.0);
    let south = grid.sample_m(-89.9 * degrees, 0.0);

    assert!(north < -3000.0, "північний полюс — океан, а вийшло {north}");
    assert!(
        south > 2000.0,
        "південний полюс — лід (продукт surface, не bed), а вийшло {south}"
    );
}

/// Довготу ловить пара дзеркальних меридіанів на одній широті.
///
/// 28° пн.ш. — Гімалаї на 86.9° сх. і Мексиканська затока на 86.9° зх.
/// Дзеркально, тобто зсув на 180° (найтиповіша помилка: сітка ETOPO
/// починається з −180°, а не з нуля, як LOLA) міняє їх місцями.
#[test]
fn meridians_are_not_mirrored() {
    let Some(grid) = relief() else { return };
    let degrees = std::f64::consts::PI / 180.0;

    let east = grid.sample_m(27.99 * degrees, 86.9 * degrees);
    let west = grid.sample_m(27.99 * degrees, -86.9 * degrees);

    assert!(east > 5000.0, "Гімалаї на 86.9° сх., а вийшло {east}");
    assert!(west < -1000.0, "затока на 86.9° зх., а вийшло {west}");
}

/// Названі точки з відомими висотами — оракул на арифметику вибірки.
///
/// Значення взяті не з підручника, а з незалежної реалізації читача (Python,
/// той самий предиктор і та сама білінійна вага), тож розбіжність тут означає
/// помилку в **нашому** коді, а не в продукті. Допуск — один метр: більше
/// нема куди, бо сітка вже лежить у цілих метрах.
#[test]
fn named_points_match_an_independent_reader() {
    let Some(grid) = relief() else { return };
    let degrees = std::f64::consts::PI / 180.0;

    for (name, lat, lon, expect) in [
        ("Еверест", 27.9881, 86.925, 8054.494),
        ("Маріанська западина", 11.35, 142.20, -10291.250),
        ("Мертве море", 31.5, 35.5, -427.0),
        ("Київ", 50.45, 30.52, 151.200),
        ("центр Тихого океану", 0.0, -140.0, -4319.250),
        ("Сахара", 23.0, 13.0, 736.500),
    ] {
        let got = grid.sample_m(lat * degrees, lon * degrees);
        assert!(
            (got - expect).abs() < 1.0,
            "{name}: {got:.3} проти {expect:.3}"
        );
    }
}

/// Вибірка за напрямком — те, чим користується сам кукер.
///
/// Окремо від `sample_m`, бо між ними стоїть переклад напрямку в кути
/// (`lat_lon`), і саме там живе третя копія помилки зі знаком.
///
/// ⚠ Порівняння з допуском, а не бітове: кут → напрямок → кут проходить через
/// `cos`, `sin` і `atan2`, і повернутися бітово туди, звідки вийшов, не
/// зобов'язаний. Бітова рівність тут потрібна не між кутами, а між вузлами
/// сусідніх патчів — і вона забезпечена інакше, спільною вершиною (R2b).
#[test]
fn direction_agrees_with_angles() {
    let Some(grid) = relief() else { return };
    let degrees = std::f64::consts::PI / 180.0;

    let (lat, lon) = (50.45 * degrees, 30.52 * degrees);
    let unit = [lat.cos() * lon.cos(), lat.cos() * lon.sin(), lat.sin()];

    let there = grid.sample_direction_m(unit);
    let here = grid.sample_m(lat, lon);
    assert!(
        (there - here).abs() < 1e-6,
        "напрямок дав {there}, кути — {here}"
    );
}
